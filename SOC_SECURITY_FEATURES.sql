
CREATE DATABASE SOC_ALERT_SYSTEM ; 
USE SOC_ALERT_SYSTEM ;
CREATE TABLE ANALYST (
    ANALYST_NAME VARCHAR(50),
    ANALYST_ID INT PRIMARY KEY,
    ANALYST_ROLE VARCHAR(50),
    ANALYST_DEPT VARCHAR(50)
);

CREATE TABLE ALERT (
    ATTACK_ID INT PRIMARY KEY,
    ATTACK_NAME VARCHAR(50),
    ATTACKER_DATA VARCHAR(50),
    ATTACKER_DATA_ID INT,
    ANALYST_ID INT,
    FOREIGN KEY (ANALYST_ID) REFERENCES ANALYST(ANALYST_ID) , 
    SEVERITY VARCHAR(50) DEFAULT 'MEDIUM'
);


CREATE TABLE FORENSIC (
    EVIDENCE_ID INT PRIMARY KEY,
    EVIDENCE_NAME VARCHAR(50),
    ATTACK_ID INT,
    ANALYST_ID INT,
    FOREIGN KEY (ATTACK_ID) REFERENCES ALERT(ATTACK_ID),
    FOREIGN KEY (ANALYST_ID) REFERENCES ANALYST(ANALYST_ID)
);

CREATE TABLE HELP_DEPT  (
HELP_DEPT_NAME VARCHAR(50) NOT NULL , 
HELP_DEPT_ID INT  PRIMARY KEY , 
ANALYST_ID INT NOT NULL , FOREIGN KEY (ANALYST_ID) references ANALYST(ANALYST_ID)  , 
EVIDENCE_ID INT NOT NULL , foreign key (EVIDENCE_ID) REFERENCES FORENSIC(EVIDENCE_ID)
) ; 

